-- Pick the tree stage that matches an hour of the day (0-23).
-- opts.hour: the hour. The default is the current hour.
-- opts.boxed: use the boxed variants.
-- opts.default: the fallback ascii for a bad hour value.
Bonsai.pick = function(opts)
	opts = opts or {}
	local hour = tonumber(opts.hour) or tonumber(vim.fn.strftime("%H"))
	local stages = opts.boxed and Bonsai.trees.boxed or Bonsai.trees.unboxed

	local interval = 24 / #stages
	local index = math.floor(hour / interval)
	return stages[index + 1] or opts.default
end

return Bonsai
